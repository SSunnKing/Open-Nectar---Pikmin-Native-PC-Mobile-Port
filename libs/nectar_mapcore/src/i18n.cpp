void setLanguage(Language lang) { gLanguage = lang; }
Language language() { return gLanguage; }
Language languageFromCode(const std::string& code) { return code == "es" ? Language::Spanish : Language::English; }
const char* languageCode(Language lang) { return lang == Language::Spanish ? "es" : "en"; }

const char* tr(const char* es)
{
	if (!es || gLanguage == Language::Spanish) return es;
	const auto& m = englishTable();
	auto it       = m.find(es);
	return it != m.end() ? it->second : es;
}

